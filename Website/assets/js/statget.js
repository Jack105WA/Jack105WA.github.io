import { db } from "./firebase-config.js";
import {
    doc,
    runTransaction,
    increment
} from "https://www.gstatic.com/firebasejs/13.1.0/firebase-firestore.js";

const hitsElement = document.getElementById("nc-hits");
const updatedElement = document.getElementById("nc-last_updated");
const STATS_DOCUMENT = doc(db, "siteStats", "counters");

function formatDate(value) {
    const date = new Date(value);
    if (Number.isNaN(date.getTime())) throw new Error("Invalid deployment commit date.");
    return date.toLocaleString("en-US", {
        month: "short", day: "numeric", year: "numeric",
        hour: "numeric", minute: "2-digit", hour12: true
    });
}

async function updateHits() {
    if (!hitsElement) return;
    try {
        const newHits = await runTransaction(db, async (transaction) => {
            const snapshot = await transaction.get(STATS_DOCUMENT);
            if (!snapshot.exists()) throw new Error('Firestore document "siteStats/counters" does not exist.');
            const currentHits = snapshot.data().hits;
            if (!Number.isInteger(currentHits) || currentHits < 0) throw new Error("Invalid Firestore hits value.");
            transaction.update(STATS_DOCUMENT, { hits: increment(1) });
            return currentHits + 1;
        });
        hitsElement.textContent = newHits.toLocaleString();
    } catch (error) {
        console.error("Could not update Firebase hit counter:", error);
        hitsElement.textContent = "Unavailable";
    }
}

async function updateLastUpdated() {
    if (!updatedElement) return;
    try {
        // Generated by GitHub Actions during deployment; no GitHub API request is made by visitors.
        const response = await fetch("/last-updated.json", { cache: "no-store" });
        if (!response.ok) throw new Error("Commit metadata returned HTTP " + response.status);
        const metadata = await response.json();
        if (!metadata.commitDate) throw new Error("Commit date is missing.");
        updatedElement.textContent = formatDate(metadata.commitDate);
    } catch (error) {
        console.error("Could not load deployment commit date:", error);
        updatedElement.textContent = "Unavailable";
    }
}

updateHits();
updateLastUpdated();
